export function normalizeSkillName(raw: string): string {
  return raw.trim().toLowerCase().replace(/[\s_.-]+/g, " ");
}

/**
 * Matches a free-form skill name string against the taxonomy using exact match,
 * canonical ID, alias match, or substring inclusion.
 */
export function matchSkillInTaxonomy(rawSkill: string): SkillDefinition | null {
  const normalized = normalizeSkillName(rawSkill);
  if (!normalized) return null;

  // 1. Exact canonical name match
  for (const skill of SKILLS_TAXONOMY) {
    if (normalizeSkillName(skill.name) === normalized || skill.id === normalized) {
      return skill;
    }
  }

  // 2. Exact alias match
  for (const skill of SKILLS_TAXONOMY) {
    for (const alias of skill.aliases) {
      if (normalizeSkillName(alias) === normalized) {
        return skill;
      }
    }
  }

  // 3. Substring matching for multi-word or compound skills
  if (normalized.length >= 3) {
    for (const skill of SKILLS_TAXONOMY) {
      const canon = normalizeSkillName(skill.name);
      if (normalized.startsWith(canon + " ") || normalized.endsWith(" " + canon)) {
        return skill;
      }
      for (const alias of skill.aliases) {
        const a = normalizeSkillName(alias);
        if (a.length >= 3 && (normalized.startsWith(a + " ") || normalized.endsWith(" " + a))) {
          return skill;
        }
      }
    }
  }

  return null;
}

/**
 * Extracts and categorizes all skills mentioned in freeform text using the taxonomy.
 */
export function extractSkillsFromText(text: string): { matchedSkills: SkillDefinition[]; matchedIds: string[] } {
  const matchedMap = new Map<string, SkillDefinition>();
  const lower = text.toLowerCase();

  for (const skill of SKILLS_TAXONOMY) {
    const candidates = [skill.name, skill.id, ...skill.aliases];
    for (const cand of candidates) {
      const escaped = cand.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
      const regex = new RegExp(`(?:^|[^a-zA-Z0-9#+])${escaped}(?:$|[^a-zA-Z0-9#+])`, "i");
      if (regex.test(lower)) {
        matchedMap.set(skill.id, skill);
        break;
      }
    }
  }

  const matchedSkills = Array.from(matchedMap.values());
  return {
    matchedSkills,
    matchedIds: matchedSkills.map((s) => s.name),
  };
}
