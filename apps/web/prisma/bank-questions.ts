import { Prisma } from "@prisma/client";

export type BankQuestion = {
  type: QuestionType;
  text: string;
  difficulty: Difficulty;
  skillTags: string[];
  expectedPoints: Prisma.InputJsonValue;
  starterCode?: Prisma.InputJsonValue;
  testCases?: Prisma.InputJsonValue;
  constraints?: string;
  examples?: Prisma.InputJsonValue;
};

function starters(python: string, javascript: string, java: string, cpp: string, c: string) {
  return { python, javascript, java, cpp, c };
}

function tests(
  cases: { input: string; expected: string; hidden?: boolean }[],
): Prisma.InputJsonValue {
  return cases.map((c) => ({
    input: c.input,
    expected: c.expected,
    hidden: Boolean(c.hidden),
  }));
}

